// Runs the GPU spec (bw.webgl.test.ts) through a SafeLight checkout's WebGL
// test harness: headless Chromium on SwiftShader, the real renderer and the
// real stage injection, so the stages are checked where the node suite can't
// see: compilation with the host's namespacing, the gate, and the shader
// against the TS twin.
//
// The spec is copied into the checkout for the run (its harness helpers and
// path aliases only resolve from inside) and removed again afterwards, along
// with the generated config. SAFELIGHT_CORE points at the checkout (default:
// a SafeLight directory beside this repository or beside its parent folder).
// The browser server takes a port the OS hands out, since Windows' dynamic
// port exclusions can swallow vitest's fixed default. SAFELIGHT_TEST_CHROME
// overrides the browser executable when Playwright's bundled Chromium won't
// start. Launch options go through playwright({ launchOptions }), which
// vitest 4.1 reads, and through the instance's `launch` as well.
"use strict";

const fs = require("fs");
const net = require("net");
const path = require("path");
const { spawnSync } = require("child_process");

const extension = path.resolve(__dirname, "..", "..");
const isCheckout = (dir) => fs.existsSync(path.join(dir, "vitest.webgl.config.ts"));
const candidates = process.env.SAFELIGHT_CORE
  ? [path.resolve(process.env.SAFELIGHT_CORE)]
  : [path.join(extension, "..", "SafeLight"), path.join(extension, "..", "..", "SafeLight")];
const core = candidates.find(isCheckout);
if (!core) {
  console.error(`No SafeLight checkout found (tried ${candidates.join(", ")}); set SAFELIGHT_CORE`);
  process.exit(2);
}

const specDir = path.join(core, "src", "rendering", "webgl", "__bw_gpu__");
const specFile = path.join(specDir, "bw.webgl.test.ts");
const configFile = path.join(core, "vitest.bw-gpu.config.ts");
const executablePath = process.env.SAFELIGHT_TEST_CHROME;

const config = (port) => `/// <reference types="vitest/config" />
// Generated by the Black & White extension's test/gpu/run.cjs and removed
// after the run. Same rig as vitest.webgl.config.ts, plus the extension's
// sources and its copied spec.
import path from "path";
import { readFileSync } from "fs";
import { defineConfig } from "vite";
import { playwright } from "@vitest/browser-playwright";

const pkg = JSON.parse(readFileSync(path.resolve(__dirname, "package.json"), "utf-8")) as { version: string };
const EXT = ${JSON.stringify(extension)};

export default defineConfig({
  cacheDir: "node_modules/.vite-cache-bw-gpu",
  define: { __APP_VERSION__: JSON.stringify(pkg.version) },
  resolve: {
    alias: {
      "@": path.resolve(__dirname, "src"),
      "libraw-wasm": path.resolve(__dirname, "src/raw/vendor/libraw-wasm/index.js"),
      "@bw": path.join(EXT, "src"),
      "@bw-test": path.join(EXT, "test"),
    },
  },
  server: { fs: { allow: [__dirname, EXT] } },
  optimizeDeps: { exclude: ["libraw-wasm"] },
  test: {
    name: "bw-gpu",
    include: ["src/rendering/webgl/__bw_gpu__/*.webgl.test.ts"],
    testTimeout: 600_000,
    browser: {
      enabled: true,
      headless: true,
      provider: playwright({
        launchOptions: {
          ${executablePath ? `executablePath: ${JSON.stringify(executablePath)},` : ""}
          args: ["--use-gl=angle", "--use-angle=swiftshader", "--enable-unsafe-swiftshader"],
        },
      }),
      api: { port: ${port}, strictPort: true },
      // Also per instance: the local rig on this machine has passed system
      // Chrome this way, and setting both costs nothing.
      instances: [
        {
          browser: "chromium",
          launch: {
            ${executablePath ? `executablePath: ${JSON.stringify(executablePath)},` : ""}
            args: ["--use-gl=angle", "--use-angle=swiftshader", "--enable-unsafe-swiftshader"],
          },
        },
      ],
    },
  },
});
`;

function freePort() {
  return new Promise((resolve, reject) => {
    const server = net.createServer();
    server.unref();
    server.on("error", reject);
    server.listen(0, "127.0.0.1", () => {
      const { port } = server.address();
      server.close(() => resolve(port));
    });
  });
}

async function main() {
  const port = await freePort();
  let status = 1;
  try {
    fs.mkdirSync(specDir, { recursive: true });
    fs.copyFileSync(path.join(__dirname, "bw.webgl.test.ts"), specFile);
    fs.writeFileSync(configFile, config(port));
    const result = spawnSync("npx", ["vitest", "run", "--config", path.basename(configFile), "--reporter=verbose"], {
      cwd: core,
      stdio: "inherit",
      shell: true,
    });
    status = result.status ?? 1;
  } finally {
    fs.rmSync(specDir, { recursive: true, force: true });
    fs.rmSync(configFile, { force: true });
  }
  process.exit(status);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
